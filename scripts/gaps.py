#!/usr/bin/env python3
"""What each entry is missing, for the review copy (gaps.tex -> Wallace-CV-gaps.pdf).

    python3 scripts/gaps.py           # write data/gaps.tex
    python3 scripts/gaps.py --check   # exit 1 if it is out of step
    python3 scripts/gaps.py --list    # the gaps, one entry per line

data/gaps.tex holds one \\setentrygap{key}{what is missing} per entry. The template
prints it under the entry, in orange, only in the review copy (gaps.tex sets
\\cvshowgaps); main.pdf and apr.pdf never show it. The template also marks a grant's
blank cells and an undefined \\cvnumber there by itself. python3 scripts/generate.py runs
this with the other generators, and check_cv.py warns when data/gaps.tex is stale, so the
review copy always shows what the record lacks today.

The rules (what counts as missing) are the CV's, from CLAUDE.md:
- printed papers (journal, conference, abstracts): a DOI (unless `nodoi`), pages (or an
  article number), and an acceptance rate or impact factor (unless data/metrics.yaml says
  `none`; `unresolved` shows the date it was last looked for). Work in press or "Just
  Accepted" is missing its final details until the weekly run backfills them.
- students (supervision.bib): program (not for postdocs) and start year; once finished, thesis title,
  date and position. Undergraduate research assistants (degree RA) hold a term-length
  appointment with no thesis, so they need neither a thesis title nor a start year.
- committees: the thesis title once the student has defended.
- courses: enrolment, and Student Course Perceptions responses and scores.
- the "so what?" facts (CLAUDE.md -> Entry detail; Jim, 2026-11-22):
  - a paper with an award icon: the award's tier ("top 5% of submissions", "one of 30");
  - a workshop or meetup Jim co-organized (note "Workshop proposal." / "Meetup."): how
    many took part;
  - chairing a conference or track (service.bib, activities.bib: a chair or convener role
    with level organizing) held in the review period: attendance, and for general, program,
    papers and technical program chairs the submissions;
  - an editorial role (level editorial) in the review period: its load ("12 submissions").
  Roles before the review period, and events still to come, are not checked.
A gap Jim knows can't be filled goes in data/gaps.yaml (`key: field, field | reason`),
which keeps it out of the review copy; only Jim adds lines there.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cvlib import ROOT, parse_bib, parse_categories, review_period, tex_escape  # noqa: E402

OUT = Path("data") / "gaps.tex"
HEADER = [
    "% Generated by scripts/gaps.py from the .bib files, main.tex, data/metrics.yaml and",
    "% data/gaps.yaml; do not edit. Printed only in the review copy (gaps.tex). The",
    "% definitions below stand in until the template provides \\setentrygap and \\cvgap.",
    r"\providecommand\setentrygap[2]{}",
    r"\providecommand\cvgap[1]{}",
]
PAPERS = ("journal", "conference", "abstracts")
METRIC = re.compile(r"Acceptance rate|Impact Factor", re.I)
PENDING = re.compile(r"in press|just accepted", re.I)
# the "so what?" facts (CLAUDE.md -> Entry detail)
ATTENDANCE = re.compile(r"\b\d[\d,]*\s+(?:[\w-]+\s+){0,2}(?:attendees|participants|people|"
                        r"researchers|students)\b|attendance", re.I)
SUBMISSIONS = re.compile(r"submission", re.I)
TIER = re.compile(r"\btop\s+\d|\bone of\b|\b\d[\d,]*\s+of\s+\d", re.I)
ORGANIZED = re.compile(r"^\s*(?:Workshop proposal|Meetup)\.", re.I)
CHAIR = re.compile(r"chair|convener", re.I)
SELECTS = re.compile(r"general chair|program chair|papers chair|technical program", re.I)


def load_lines(path: Path) -> dict[str, list[str]]:
    """data/metrics.yaml or data/gaps.yaml: {key: [first field, rest...]} split on |."""
    out = {}
    if not path.exists():
        return out
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or ":" not in line:
            continue
        key, rest = line.split(":", 1)
        out[key.strip()] = [p.strip() for p in rest.split("|")]
    return out


def accepted(root: Path) -> dict[str, set[str]]:
    """data/gaps.yaml: {key: fields Jim has accepted as missing}."""
    return {k: {f.strip() for f in v[0].split(",") if f.strip()}
            for k, v in load_lines(root / "data" / "gaps.yaml").items()}


def paper_gaps(e, metric: list[str] | None) -> list[str]:
    f = e.fields
    gaps = []
    if PENDING.search(f.get("note", "")):
        gaps.append("final publication details (in press)")
    if not f.get("doi") and not f.get("nodoi"):
        gaps.append("DOI")
    if not f.get("pages") and not f.get("articleno") and not f.get("eid"):
        gaps.append("pages")
    if not METRIC.search(f.get("note", "")):
        if metric is None:
            gaps.append("acceptance rate or impact factor")
        elif metric[0] == "unresolved":
            when = f", last looked for {metric[2]}" if len(metric) > 2 and metric[2] else ""
            gaps.append(f"acceptance rate or impact factor (unresolved{when})")
    note = f.get("note", "")
    if f.get("icon") and not TIER.search(note):
        gaps.append("award tier")
    if ORGANIZED.match(note) and not ATTENDANCE.search(note):
        gaps.append("attendance")
    return gaps


def years_of(f: dict) -> tuple[int | None, int | None]:
    """(first, last) year of a service record: its `years` if given, else its date; last is
    None for an ongoing role (date = {2021/})."""
    date = f.get("date", "")
    found = [int(y) for y in re.findall(r"\d{4}", f.get("years", "") or date)]
    if not found:
        return None, None
    if date.rstrip().endswith("/") and not f.get("years"):
        return found[0], None
    return found[0], found[-1]


def service_gaps(e, period: tuple[int, int] | None) -> list[str]:
    """Chairing an event in the review period: attendance (and submissions for the chairs
    who select the program); an editorial role in the period: its load."""
    f = e.fields
    if not period:
        return []
    levels = {x.strip() for x in f.get("level", "").split(",")}
    role, note = f.get("role", ""), f.get("note", "")
    first, last = years_of(f)
    gaps = []
    if "organizing" in levels and CHAIR.search(role) and last is not None \
            and period[0] <= last <= period[1]:
        if not ATTENDANCE.search(note):
            gaps.append("attendance")
        if SELECTS.search(role) and not SUBMISSIONS.search(note):
            gaps.append("submissions")
    if "editorial" in levels and first is not None and first <= period[1] \
            and (last is None or last >= period[0]) and not re.search(r"\d", note):
        gaps.append("load")
    return gaps


def student_gaps(e) -> list[str]:
    f = e.fields
    ra = f.get("degree", "").upper() == "RA"
    gaps = [] if f.get("program") or f.get("degree", "").upper() == "PDF" else ["program"]
    gaps += [] if f.get("started") or ra else ["start year"]
    if f.get("status") != "In progress":
        gaps += [name for field, name in (("date", "date"), ("title", "thesis title"),
                                          ("position", "position"))
                 if not f.get(field) and not (ra and field == "title")]
    return gaps


def committee_gaps(e) -> list[str]:
    f = e.fields
    if f.get("count"):
        return []
    return ["thesis title"] if "defended" in f.get("note", "") and not f.get("title") else []


def course_gaps(e) -> list[str]:
    f = e.fields
    return [name for field, name in (("enrolment", "enrolment"), ("responses", "SCP responses"),
                                     ("scp", "SCP scores")) if not f.get(field)]


FIELD_OF = {  # the name a gap prints as -> the word data/gaps.yaml uses for it
    "final publication details (in press)": "inpress", "DOI": "doi", "pages": "pages",
    "program": "program", "start year": "started", "date": "date",
    "thesis title": "title", "position": "position", "enrolment": "enrolment",
    "SCP responses": "responses", "SCP scores": "scp", "award tier": "tier",
    "attendance": "attendance", "submissions": "submissions", "load": "load",
}


def field_of(gap: str) -> str:
    return "metric" if gap.startswith("acceptance rate") else FIELD_OF.get(gap, gap)


def gaps(root: Path = ROOT) -> list[tuple[str, list[str]]]:
    """[(key, [what is missing])] for every printed entry with a gap, in file order."""
    cats = parse_categories(root / "main.tex")
    metrics = load_lines(root / "data" / "metrics.yaml")
    ok = accepted(root)
    out: list[tuple[str, list[str]]] = []

    def add(key, found):
        found = [g for g in found if field_of(g) not in ok.get(key, set())]
        if found:
            out.append((key, found))

    printed = {k for c in PAPERS for k in cats.get(c, [])}
    for e in parse_bib(root / "scholar.bib").entries:
        if e.key in printed:
            add(e.key, paper_gaps(e, metrics.get(e.key)))
    for name, rule in (("supervision.bib", student_gaps), ("committees.bib", committee_gaps),
                       ("courses.bib", course_gaps)):
        if (root / name).exists():
            for e in parse_bib(root / name).entries:
                add(e.key, rule(e))
    period = review_period(root / "main.tex")
    for name in ("service.bib", "activities.bib"):
        if (root / name).exists():
            for e in parse_bib(root / name).entries:
                add(e.key, service_gaps(e, period))
    return out


def build(root: Path = ROOT) -> tuple[str, list[str]]:
    found = gaps(root)
    lines = HEADER + [f"% {len(found)} entries with gaps"]
    lines += [rf"\setentrygap{{{key}}}{{{tex_escape(', '.join(g))}}}" for key, g in found]
    return "\n".join(lines) + "\n", []


def main(argv: list[str]) -> int:
    out = ROOT / OUT
    if "--list" in argv:
        for key, g in gaps():
            print(f"{key}: {', '.join(g)}")
        return 0
    text, _ = build()
    if "--check" in argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of step; run python3 scripts/generate.py", file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}: {len(gaps())} entries with gaps")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
