#!/usr/bin/env python3
"""Counts that the APR narratives quote, generated from the record so that a sentence
Jim wrote stays true as the record grows.

    python3 scripts/cv_numbers.py           # write data/cv-numbers.tex
    python3 scripts/cv_numbers.py --check   # exit 1 if it is out of step
    python3 scripts/cv_numbers.py --list    # name, value and meaning of every number

data/cv-numbers.tex defines one \\setcvnumber{name}{value} per number, and main.tex
prints one with \\cvnumber{name}, e.g.

    Trainees are first authors on \\cvnumber{review-works-trainee-first} of the
    \\cvnumber{review-works} papers and presentations I published or gave in 2025--26

Only counts that change as the record grows are here: review-period output and who led it
(scholar.bib and main.tex), the SciVal figures (data/citation-impact.yaml), venues
(data/venues.yaml) and funders (data/funders.yaml). Fixed historical facts (an
acceptance rate, a grant's amount) are not, and nor are figures the repository doesn't
hold (SciVal topic totals). check_cv.py fails on \\cvnumber of a name not defined here, and
warns when main.tex hard-codes a number that has one (HINTS) or when the file is out of
step. python3 scripts/generate.py runs this with the other generators.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cvlib import (ROOT, in_review_period, is_marked_trainee, parse_bib,  # noqa: E402
                   parse_categories, review_period)

OUT = Path("data") / "cv-numbers.tex"
HEADER = [
    "% Generated by scripts/cv_numbers.py from scholar.bib, main.tex, grants.bib and data/*.yaml;",
    "% do not edit. main.tex prints a number with \\cvnumber{name}; the definitions below",
    "% stand in until the template provides \\setcvnumber and \\cvnumber.",
    r"\providecommand\setcvnumber[2]{\expandafter\def\csname cvnumber/#1\endcsname{#2}}",
    r"\providecommand\cvnumber[1]{\ifcsname cvnumber/#1\endcsname\csname cvnumber/#1\endcsname"
    r"\else\textbf{??}\fi}",
]
# The review-period groups the supervision note counts ("4 of 5 journal articles, 9 of 11
# conference papers and 15 of 18 presentations").
GROUPS = {
    "journal": ["journal"],
    "conference": ["conference", "abstracts"],
    "presentations": ["presentations", "invited"],
}
# A hard-coded number in main.tex that has a \cvnumber: (pattern, the names to use).
# Patterns match Jim's current wording only, so a rewritten sentence never warns falsely.
HINTS = [
    (r"first authors on \d+ of the \d+", ["review-works-trainee-first", "review-works"]),
    (r"\d+ of \d+ journal articles", ["review-journal-trainee-first", "review-journal"]),
    (r"\d+ of \d+ conference papers", ["review-conference-trainee-first", "review-conference"]),
    (r"\d+ of \d+ presentations", ["review-presentations-trainee-first", "review-presentations"]),
    (r"first-authored \d+ of the \d+ papers", ["scival-top-trainee-first", "scival-top"]),
    (r"Of my \d+ Scopus-indexed papers", ["scival-papers"]),
    (r"Scopus-indexed papers published up to \d{4}, \d+ \(\d+", ["scival-last-year", "scival-top",
                                                                  "scival-top-share"]),
]


def first_author(e) -> str:
    return (e.fields.get("author", "") or "").split(" and ")[0]


def scival(root: Path) -> tuple[int | None, int, list[tuple[str, int, int]]]:
    """(export year, threshold, [(key, percentile, year)]) from data/citation-impact.yaml."""
    path = root / "data" / "citation-impact.yaml"
    if not path.exists():
        return None, 10, []
    exported, threshold, rows = None, 10, []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line or ":" not in line:
            continue
        k, v = (s.strip() for s in line.split(":", 1))
        if k == "exported":
            exported = int(v[:4])
        elif k == "threshold":
            threshold = int(v)
        else:
            parts = [s.strip() for s in v.split("|")]
            rows.append((k, int(parts[0]), int(parts[3])))
    return exported, threshold, rows


def numbers(root: Path = ROOT) -> tuple[list[tuple[str, int, str]], list[str]]:
    """[(name, value, meaning)] and problems (from the venue and funder data)."""
    import funder_profile
    import venue_profile
    bib = {e.key: e for e in parse_bib(root / "scholar.bib").entries}
    cats = parse_categories(root / "main.tex")
    period = review_period(root / "main.tex")
    include, exclude = set(cats.get("aprinclude", [])), set(cats.get("aprnone", []))
    out: list[tuple[str, int, str]] = []
    problems: list[str] = []

    if period:
        span = f"{period[0]}--{period[1]}"
        total = led = 0
        for group, group_cats in GROUPS.items():
            keys = [k for c in group_cats for k in dict.fromkeys(cats.get(c, []))
                    if k in bib and in_review_period(bib[k], k, period, include, exclude)]
            n_led = sum(1 for k in keys if is_marked_trainee(first_author(bib[k])))
            out += [(f"review-{group}", len(keys), f"{' and '.join(group_cats)} entries in {span}"),
                    (f"review-{group}-trainee-first", n_led, f"... of which a trainee is first author")]
            total, led = total + len(keys), led + n_led
        out += [("review-works", total, f"journal, conference and presentation entries in {span}"),
                ("review-works-trainee-first", led, "... of which a trainee is first author")]

    exported, threshold, rows = scival(root)
    if exported:
        # as citation_impact.py: too new otherwise; the year is the CV's (scholar.bib)
        cited = [r for r in rows if (bib[r[0]].year if r[0] in bib and bib[r[0]].year else r[2]) < exported]
        top = [r for r in cited if r[1] <= threshold]
        top_led = sum(1 for k, _, _ in top if k in bib and is_marked_trainee(first_author(bib[k])))
        out += [("scival-last-year", exported - 1, "the last publication year the SciVal counts include"),
                ("scival-papers", len(cited), "Scopus-indexed papers published up to that year"),
                ("scival-top", len(top), f"... of which in the top {threshold}% of field-weighted citations"),
                ("scival-top-share", round(100 * len(top) / len(cited)) if cited else 0,
                 "... as a percentage"),
                ("scival-top-trainee-first", top_led, "... of which a trainee is first author")]

    classified, venue_problems = venue_profile.classify(root)
    problems += venue_problems
    for kind, label in (("journal", "journals"), ("proceedings", "proceedings")):
        items = classified[kind]
        out += [(label, len(items), f"{kind} entries classified in data/venues.yaml"),
                (f"{label}-health", sum(1 for _, v, _ in items if v.get("field") == "health"),
                 "... of which at health venues")]

    grants, funder_problems = funder_profile.grants_by_funder(root)
    problems += funder_problems
    funded = [(e, f) for e, f in grants if "status" not in e.fields]
    out += [("grants-funded", len(funded), "funded grants in grants.bib"),
            ("grants-funded-health", sum(1 for _, f in funded if f.get("sector") == "health"),
             "... of which from health research funders (data/funders.yaml)")]
    return out, problems


def build(root: Path = ROOT) -> tuple[str, list[str]]:
    nums, problems = numbers(root)
    if problems:
        return "", problems
    lines = HEADER + [rf"\setcvnumber{{{name}}}{{{value}}}" for name, value, _ in nums]
    return "\n".join(lines) + "\n", []


def used(main_tex: str) -> set[str]:
    """The names main.tex prints with \\cvnumber (comments included: a commented-out
    paragraph Jim may restore should stay in step too)."""
    return set(re.findall(r"\\cvnumber\{([^}]*)\}", main_tex))


def hard_coded(main_tex: str) -> list[tuple[str, list[str]]]:
    """(the text, the \\cvnumber names to use) for each HINTS pattern main.tex matches."""
    return [(m.group(0), names) for pattern, names in HINTS
            for m in re.finditer(pattern, main_tex)]


def main(argv: list[str]) -> int:
    out = ROOT / OUT
    if "--list" in argv:
        nums, problems = numbers()
        for name, value, meaning in nums:
            print(f"{name:36} {value:>5}  {meaning}")
        return 1 if problems else 0
    text, problems = build()
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    if "--check" in argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of step; run python3 scripts/generate.py", file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
