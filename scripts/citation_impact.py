#!/usr/bin/env python3
"""Citation-impact notes from a SciVal publication export.

    python3 scripts/citation_impact.py EXPORT.csv   # import a new export, then regenerate
    python3 scripts/citation_impact.py              # regenerate from data/citation-impact.yaml

Importing reads SciVal's "Publications of ..." CSV export, matches each output
to a scholar.bib entry by DOI (else by title and year), and rewrites data/citation-impact.yaml with the
few figures the CV uses (the raw export, with abstracts and Scopus ids, is not
kept in this public repository). Outputs it cannot match are listed on stdout.

Regenerating writes data/citation-impact.tex: one \\setentrydetail{key}{...}
line (template) for every entry whose field-weighted citation percentile is
within the threshold in the YAML file, printed under the entry in both PDFs.
Work published in the export's year is left out (too new to be cited):

    Top 3% most cited in its field (field-weighted citation impact 5.93; SciVal, November 2026)

The percentile is SciVal's "Field-Weighted Outputs in Top Citation
Percentiles": the output's rank among all Scopus outputs of the same subject
field, publication year and type. Never edit either data file by hand.
"""
from __future__ import annotations

import csv
import datetime as dt
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cvlib import norm_title, parse_bib  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "citation-impact.yaml"
OUT_TEX = ROOT / "data" / "citation-impact.tex"
DEFAULT_THRESHOLD = 10
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August",
          "September", "October", "November", "December"]

COL_FWCI = "Field-Weighted Citation Impact"
COL_FWTOP = "Field-Weighted Outputs in Top Citation Percentiles, per percentile"
COL_CITES = "Citations"


def norm_doi(d: str) -> str:
    d = d.strip().lower()
    return re.sub(r"^https?://(dx\.)?doi\.org/", "", d)


def read_export(path: Path) -> tuple[dict[str, str], list[dict[str, str]]]:
    lines = path.read_text(encoding="utf-8-sig").splitlines()
    meta = {}
    for row in csv.reader(lines):
        if row and row[0] == "Title":
            break
        if len(row) >= 2:
            meta[row[0].strip()] = row[1].strip()
    start = next(i for i, l in enumerate(lines) if l.startswith('"Title"'))
    rows = [r for r in csv.DictReader(lines[start:]) if r.get("Title") and r.get("DOI") is not None]
    return meta, rows


def import_export(path: Path) -> None:
    meta, rows = read_export(path)
    exported = dt.datetime.strptime(meta["Date exported"], "%d %B %Y").date()
    updated = meta.get("Date last updated", "")
    by_doi, by_title = {}, {}
    for e in parse_bib(ROOT / "scholar.bib").entries:
        d = norm_doi(e.fields.get("doi", ""))
        if d:
            by_doi.setdefault(d, e.key)
        t = norm_title(e.fields.get("title", ""))
        if t:
            by_title.setdefault((t, e.year), e.key)
    threshold = load()[1] if DATA.exists() else DEFAULT_THRESHOLD
    out, unmatched = [], []
    for r in rows:
        doi = norm_doi(r.get("DOI", ""))
        key = by_doi.get(doi) if doi not in ("", "-") else None
        if not key:  # no DOI, or another DOI for the same work: same title and year
            key = by_title.get((norm_title(r["Title"]), int(r["Year"])))
        if not key:
            unmatched.append(f"  {r['Year']}  {doi or '(no DOI)'}  {r['Title'][:70]}")
            continue
        top, fwci = r.get(COL_FWTOP, "-"), r.get(COL_FWCI, "-")
        if top in ("", "-") or fwci in ("", "-"):
            continue
        out.append((int(top), -float(fwci), key, fwci, r.get(COL_CITES, "0"), r["Year"]))
    out.sort()
    with DATA.open("w", encoding="utf-8") as f:
        f.write("# Citation impact from SciVal (Scopus data), generated by\n"
                "# scripts/citation_impact.py from a SciVal publication export; do not edit.\n"
                "# key: field-weighted top citation percentile | field-weighted citation impact | citations | year\n"
                f"# Scopus data last updated {updated}.\n"
                f"exported: {exported.isoformat()}\n"
                f"threshold: {threshold}\n")
        for top, _, key, fwci, cites, year in out:
            f.write(f"{key}: {top} | {fwci} | {cites} | {year}\n")
    print(f"{len(out)} outputs matched; {len(unmatched)} not in scholar.bib:")
    print("\n".join(unmatched))


def load(data: Path = DATA) -> tuple[dt.date, int, list[tuple[str, int, str, int]]]:
    exported, threshold, recs = None, DEFAULT_THRESHOLD, []
    for line in data.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        k, v = (s.strip() for s in line.split(":", 1))
        if k == "exported":
            exported = dt.date.fromisoformat(v)
        elif k == "threshold":
            threshold = int(v)
        else:
            top, fwci, _, year = (s.strip() for s in v.split("|"))
            recs.append((k, int(top), fwci, int(year)))
    return exported, threshold, recs


OUT = OUT_TEX.relative_to(ROOT)


def build(root: Path = ROOT) -> tuple[str, list[str]]:
    """(data/citation-impact.tex, problems) from data/citation-impact.yaml, for
    scripts/generate.py. No problems: the YAML is itself generated."""
    exported, threshold, recs = load(root / DATA.relative_to(ROOT))
    when = f"{MONTHS[exported.month - 1]} {exported.year}"
    lines = ["% Generated by scripts/citation_impact.py from data/citation-impact.yaml; do not edit.",
             f"% Entries in the top {threshold}% of field-weighted citations (SciVal), published",
             f"% before {exported.year}; printed under the entry in both PDFs (\\setentrydetail, template)."]
    for key, top, fwci, year in recs:
        # Work published in the export's year has not had time to be cited; the
        # APR note on research contributions leaves it out too.
        if top <= threshold and year < exported.year:
            lines.append(f"\\setentrydetail{{{key}}}{{\\textbf{{Top {top}\\% most cited in its field}} "
                         f"(field-weighted citation impact {fwci}; SciVal, {when})}}")
    return "\n".join(lines) + "\n", []


def generate() -> None:
    text, _ = build()
    OUT_TEX.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}: {text.count(chr(10)) - 3} entries")


if __name__ == "__main__":
    if len(sys.argv) > 1:
        import_export(Path(sys.argv[1]))
    generate()
