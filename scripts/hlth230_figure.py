#!/usr/bin/env python3
"""Draw figures/hlth230-grades.tex (plain TikZ) from data/hlth230-grades.csv.

    python3 scripts/hlth230_figure.py

Plain TikZ rather than pgfplots: under TeX Live 2026 with \\DocumentMetadata
(PDF/A), pgfplots runs TeX out of main memory. Re-run after editing the CSV.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
rows = list(csv.DictReader(open(ROOT / "data/hlth230-grades.csv", encoding="utf-8")))

W, H = 15.0, 5.2            # plot area, cm
YMIN, YMAX = 60.0, 104.0
n = len(rows)
dx = W / n


def X(i):
    return dx * (i + 0.5)


def Y(v):
    return (v - YMIN) / (YMAX - YMIN) * H


def num(s):
    return None if s.strip().lower() in ("", "nan") else float(s)


SERIES = [  # column, colour, line style, legend label
    ("mean", "blue!70!black", "solid", "Mean"),
    ("median", "green!50!black", "solid", "Median"),
    ("mode", "orange!85!black", "dashed", "Mode"),
]

out = ["% Generated by scripts/hlth230_figure.py from data/hlth230-grades.csv; do not edit.",
       "% HLTH 230 final course grades by term (APR version only). Shaded: terms Jim taught.",
       "\\begin{center}",
       "\\begin{tikzpicture}[x=1cm, y=1cm, font=\\scriptsize]"]
# shaded terms
for i, r in enumerate(rows):
    if r["mine"].strip() == "1":
        out.append(f"\\fill[black!8] ({X(i)-dx/2:.3f},0) rectangle ({X(i)+dx/2:.3f},{H:.3f});")
# grid and y labels
for v in range(60, 101, 10):
    out.append(f"\\draw[black!12] (0,{Y(v):.3f}) -- ({W:.3f},{Y(v):.3f});")
    out.append(f"\\node[left] at (0,{Y(v):.3f}) {{{v}}};")
out.append(f"\\draw (0,0) rectangle ({W:.3f},{H:.3f});")
out.append(f"\\node[rotate=90, font=\\small] at (-0.9,{H/2:.3f}) {{Final grade (\\%)}};")
# x labels
for i, r in enumerate(rows):
    out.append(f"\\draw ({X(i):.3f},0) -- ({X(i):.3f},0.08);")
    out.append(f"\\node[rotate=60, anchor=east] at ({X(i):.3f},-0.08) {{{r['term']}}};")
# series: polylines broken at missing values, then marks
for col, colour, style, _ in SERIES:
    seg = []
    segs = [seg]
    for i, r in enumerate(rows):
        v = num(r[col])
        if v is None:
            seg = []
            segs.append(seg)
        else:
            seg.append((X(i), Y(v)))
    for s in segs:
        if len(s) > 1:
            pts = " -- ".join(f"({x:.3f},{y:.3f})" for x, y in s)
            out.append(f"\\draw[{colour}, thick, {style}] {pts};")
    for s in segs:
        for x, y in s:
            out.append(f"\\fill[{colour}] ({x:.3f},{y:.3f}) circle (1.4pt);")
# legend above the plot
lx = W / 2 - 3.0
for k, (_, colour, style, label) in enumerate(SERIES):
    x0 = lx + 2.1 * k
    y0 = H + 0.35
    out.append(f"\\draw[{colour}, thick, {style}] ({x0:.3f},{y0:.3f}) -- ({x0+0.5:.3f},{y0:.3f});")
    out.append(f"\\fill[{colour}] ({x0+0.25:.3f},{y0:.3f}) circle (1.4pt);")
    out.append(f"\\node[right] at ({x0+0.55:.3f},{y0:.3f}) {{{label}}};")
out.append("\\end{tikzpicture}")
out.append("")
out.append("\\parbox{\\linewidth}{\\footnotesize HLTH 230 final course grades by term, Winter 2017 -- "
           "Spring 2026. Shaded: terms I taught. Winter 2017 -- Spring 2025 from the University's "
           "Institutional Analysis and Planning count-date data (Quest); Winter and Spring 2026 from "
           "LEARN final grades, where the mode is not comparable and is not shown.}")
out.append("\\end{center}")
(ROOT / "figures/hlth230-grades.tex").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote figures/hlth230-grades.tex")
