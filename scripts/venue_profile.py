#!/usr/bin/env python3
"""The venue profile at the top of PUBLICATIONS: how many journal articles appear in
health, HCI and multidisciplinary journals.

    python3 scripts/venue_profile.py           # write data/venue-profile.tex
    python3 scripts/venue_profile.py --check   # exit 1 if it is out of step (check_cv.py warns too)

Reads the `journal` category in main.tex, each entry's journal in scholar.bib and the
journal's field in data/venues.yaml, and writes one sentence for both PDFs, plus one for
the APR on the articles in the review period (by year, aprinclude and aprnone, as the
highlighting does):

    Of the 24 refereed journal articles below, 9 are in health journals (...), 13 in HCI
    journals and 2 in a multidisciplinary journal (PLOS ONE). Of the 5 in the review
    period (2025--2026), 3 are in health journals.

A journal missing from data/venues.yaml stops the script; add it with its field. Never
edit data/venue-profile.tex by hand.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cvlib import ROOT, norm, parse_bib, parse_categories, review_period  # noqa: E402

FIELDS = ["health", "hci", "multidisciplinary"]
LABEL = {"health": "health", "hci": "HCI", "multidisciplinary": "multidisciplinary"}
HEADER = "% Generated by scripts/venue_profile.py from data/venues.yaml and scholar.bib; do not edit."


def load_venues(path: Path) -> list[dict]:
    """data/venues.yaml as a list of {name, field, aka}. PyYAML if present, else the
    simple layout the file uses."""
    text = path.read_text(encoding="utf-8")
    try:
        import yaml
        return (yaml.safe_load(text) or {}).get("journals", []) or []
    except ImportError:
        pass
    out: list[dict] = []
    for ln in text.splitlines():
        ln = re.sub(r"\s+#.*$", "", ln).rstrip()
        m = re.match(r"\s*-\s+name:\s*(.+)$", ln)
        if m:
            out.append({"name": m.group(1).strip().strip("'\"")})
            continue
        m = re.match(r"\s+(field|aka):\s*(.+)$", ln)
        if m and out:
            val = m.group(2).strip()
            out[-1][m.group(1)] = json.loads(val) if val.startswith("[") else val.strip("'\"")
    return out


def venue_index(venues: list[dict]) -> dict[str, dict]:
    idx = {}
    for v in venues:
        for spelling in [v["name"]] + list(v.get("aka", []) or []):
            idx[norm(spelling)] = v
    return idx


def tex_escape(s: str) -> str:
    return re.sub(r"(?<!\\)([&%#])", r"\\\1", s)


def join(items: list[str]) -> str:
    return items[0] if len(items) == 1 else ", ".join(items[:-1]) + " and " + items[-1]


def build(root: Path = ROOT) -> tuple[str, list[str]]:
    """(the .tex text, problems). Problems are journals with no field, or bad fields."""
    bib = {e.key: e for e in parse_bib(root / "scholar.bib").entries}
    cats = parse_categories(root / "main.tex")
    period = review_period(root / "main.tex")
    include = set(cats.get("aprinclude", []))
    exclude = set(cats.get("aprnone", []))
    venues = venue_index(load_venues(root / "data" / "venues.yaml"))
    problems = []
    for v in venues.values():
        if v.get("field") not in FIELDS:
            problems.append(f"data/venues.yaml: '{v['name']}' has field '{v.get('field')}', "
                            f"not one of {', '.join(FIELDS)}")
    articles = []  # (key, venue, in period)
    for key in dict.fromkeys(cats.get("journal", [])):
        e = bib.get(key)
        if e is None:
            continue
        journal = e.fields.get("journal") or e.fields.get("journaltitle") or ""
        v = venues.get(norm(journal))
        if v is None:
            problems.append(f"{key}: journal '{journal}' is not in data/venues.yaml")
            continue
        in_period = bool(period) and key not in exclude and (
            key in include or (e.year is not None and period[0] <= e.year <= period[1]))
        articles.append((key, v, in_period))
    if problems:
        return "", problems

    def count(arts, field):
        return sum(1 for _, v, _ in arts if v["field"] == field)

    def names(field):
        return sorted({v["name"] for _, v, _ in articles if v["field"] == field}, key=str.lower)

    parts = []
    for field in FIELDS:
        n = count(articles, field)
        if not n:
            continue
        label = LABEL[field]
        if len(names(field)) == 1:  # "a multidisciplinary journal", "an HCI journal"
            phrase = f"{'an' if label[0] in 'AEFHILMNORSX' else 'a'} {label} journal"
        else:
            phrase = f"{label} journals"
        verb = ("is " if n == 1 else "are ") if not parts else ""
        text = f"{n} {verb}in {phrase}"
        if field != "hci":  # the health and multidisciplinary journals are named
            text += " (" + join([r"\emph{" + tex_escape(x) + "}" for x in names(field)]) + ")"
        parts.append(text)
    line = (f"Of the {len(articles)} refereed journal articles below, " + join(parts) + "."
            if articles else "")
    lines = [HEADER, line]
    recent = [a for a in articles if a[2]]
    if period and recent:
        h = count(recent, "health")
        where = "is in a health journal" if h == 1 else "are in health journals"
        lines.append(rf"\ifAPR Of the {len(recent)} in the review period ({period[0]}--{period[1]}), "
                     f"{h} {where}.\\fi")
    return "\n".join(lines) + "\n", []


def main(argv: list[str]) -> int:
    out = ROOT / "data" / "venue-profile.tex"
    text, problems = build()
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    if "--check" in argv:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print("data/venue-profile.tex is out of step; run python3 scripts/venue_profile.py",
                  file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
