#!/usr/bin/env python3
"""The venue profile at the top of PUBLICATIONS: how many journal articles appear in
health, HCI and multidisciplinary journals.

    python3 scripts/venue_profile.py           # write data/venue-profile.tex
    python3 scripts/venue_profile.py --check   # exit 1 if it is out of step (check_cv.py warns too)

Reads the `journal` category in main.tex, each entry's journal in scholar.bib and the
journal's field in data/venues.yaml, and writes one sentence for both PDFs, plus one for
the APR on the articles in the review period (by year, aprinclude and aprnone, as the
highlighting does):

    Of the 24 refereed journal articles below, 9 are in health journals (...), 13 in HCI
    journals and 2 in a multidisciplinary journal (PLOS ONE). Of the 5 in the review
    period (2025--2026), 3 are in health journals.

A journal missing from data/venues.yaml stops the script; add it with its field. The
file's `proceedings` section tags the conference series of the `conference` and
`abstracts` categories the same way (classify(); scripts/cv_numbers.py counts them, the
printed line doesn't). python3 scripts/generate.py runs this with the other generators.
Never edit data/venue-profile.tex by hand.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cvlib import (FIELDS, ROOT, in_review_period, join_and as join, load_tagged, norm,  # noqa: E402
                   parse_bib, parse_categories, review_period, tex_escape)

OUT = Path("data") / "venue-profile.tex"
LABEL = {"health": "health", "hci": "HCI", "multidisciplinary": "multidisciplinary",
         "computing": "computing"}
HEADER = "% Generated by scripts/venue_profile.py from data/venues.yaml and scholar.bib; do not edit."
PROCEEDINGS_CATEGORIES = ["conference", "abstracts"]


def load_venues(path: Path) -> list[dict]:
    """The journals in data/venues.yaml, as {name, field, aka}."""
    return load_tagged(path).get("journals", [])


def venue_index(venues: list[dict]) -> dict[str, dict]:
    idx = {}
    for v in venues:
        for spelling in [v["name"]] + list(v.get("aka", []) or []):
            idx[norm(spelling)] = v
    return idx


def proceedings_venue(e, series: list[dict]) -> dict | None:
    """The data/venues.yaml proceedings series whose `match` occurs in the entry's
    booktitle, journal or series (ignoring case, spaces and punctuation)."""
    where = norm(" ".join(e.fields.get(f, "") or "" for f in ("booktitle", "journal", "series")))
    for v in series:
        if any(norm(m) in where for m in v.get("match", []) or []):
            return v
    return None


def classify(root: Path = ROOT) -> tuple[dict, list[str]]:
    """{"journal": [(key, venue, in period)], "proceedings": [...]}, and problems: a
    journal article or proceedings entry with no venue, or a venue with a bad field."""
    bib = {e.key: e for e in parse_bib(root / "scholar.bib").entries}
    cats = parse_categories(root / "main.tex")
    period = review_period(root / "main.tex")
    include = set(cats.get("aprinclude", []))
    exclude = set(cats.get("aprnone", []))
    tagged = load_tagged(root / "data" / "venues.yaml")
    venues = venue_index(tagged.get("journals", []))
    series = tagged.get("proceedings", [])
    problems = []
    for v in list(tagged.get("journals", [])) + list(series):
        if v.get("field") not in FIELDS:
            problems.append(f"data/venues.yaml: '{v.get('name')}' has field '{v.get('field')}', "
                            f"not one of {', '.join(FIELDS)}")
    out: dict[str, list] = {"journal": [], "proceedings": []}
    for key in dict.fromkeys(cats.get("journal", [])):
        e = bib.get(key)
        if e is None:
            continue
        journal = e.fields.get("journal") or e.fields.get("journaltitle") or ""
        v = venues.get(norm(journal))
        if v is None:
            problems.append(f"{key}: journal '{journal}' is not in data/venues.yaml")
            continue
        out["journal"].append((key, v, in_review_period(e, key, period, include, exclude)))
    if series:  # proceedings are classified once data/venues.yaml has the section
        for cat in PROCEEDINGS_CATEGORIES:
            for key in dict.fromkeys(cats.get(cat, [])):
                e = bib.get(key)
                if e is None:
                    continue
                v = proceedings_venue(e, series)
                if v is None:
                    where = e.fields.get("booktitle") or e.fields.get("journal") or "?"
                    problems.append(f"{key}: proceedings '{where[:80]}' match no proceedings "
                                    "series in data/venues.yaml")
                    continue
                out["proceedings"].append((key, v, in_review_period(e, key, period, include, exclude)))
    return out, problems


def build(root: Path = ROOT) -> tuple[str, list[str]]:
    """(the .tex text, problems). Problems are venues with no field, or bad fields."""
    classified, problems = classify(root)
    articles = classified["journal"]
    period = review_period(root / "main.tex")
    if problems:
        return "", problems

    def count(arts, field):
        return sum(1 for _, v, _ in arts if v["field"] == field)

    def names(field):
        return sorted({v["name"] for _, v, _ in articles if v["field"] == field}, key=str.lower)

    parts = []
    for field in FIELDS:
        n = count(articles, field)
        if not n:
            continue
        label = LABEL[field]
        if len(names(field)) == 1:  # "a multidisciplinary journal", "an HCI journal"
            phrase = f"{'an' if label[0] in 'AEFHILMNORSX' else 'a'} {label} journal"
        else:
            phrase = f"{label} journals"
        verb = ("is " if n == 1 else "are ") if not parts else ""
        text = f"{n} {verb}in {phrase}"
        if field != "hci":  # the health and multidisciplinary journals are named
            text += " (" + join([r"\emph{" + tex_escape(x) + "}" for x in names(field)]) + ")"
        parts.append(text)
    line = (f"Of the {len(articles)} refereed journal articles below, " + join(parts) + "."
            if articles else "")
    lines = [HEADER, line]
    recent = [a for a in articles if a[2]]
    if period and recent:
        h = count(recent, "health")
        where = "is in a health journal" if h == 1 else "are in health journals"
        lines.append(rf"\ifAPR Of the {len(recent)} in the review period ({period[0]}--{period[1]}), "
                     f"{h} {where}.\\fi")
    return "\n".join(lines) + "\n", []


def main(argv: list[str]) -> int:
    out = ROOT / OUT
    text, problems = build()
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    if "--check" in argv:
        current = out.read_text(encoding="utf-8") if out.exists() else ""
        if current != text:
            print("data/venue-profile.tex is out of step; run python3 scripts/venue_profile.py",
                  file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
