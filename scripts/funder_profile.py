#!/usr/bin/env python3
"""The health-funder sentence in "A Note on Research Funding" (APR only).

    python3 scripts/funder_profile.py           # write data/funders.tex
    python3 scripts/funder_profile.py --check   # exit 1 if it is out of step

Reads every funded grant in grants.bib (no `status`), the sector of its agency in
data/funders.yaml, and Jim's role, and writes the sentence that follows the bold lead
"Health research funders also support the work." in main.tex:

    I was PI of a Public Health Agency of Canada project (2017) and Co-PI of a Canadian
    Public Health Association project (2017--18), and a co-investigator or co-applicant
    on a Canadian Immunization Research Network project (2021--22) and three CIHR
    grants (2020--21, 2022--24 and 2025--26).

An agency missing from data/funders.yaml stops the script; add it with its sector.
python3 scripts/generate.py runs this with the other generators. Never edit
data/funders.tex by hand.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cvlib import ROOT, SECTORS, join_and, load_tagged, parse_bib, tex_escape  # noqa: E402

OUT = Path("data") / "funders.tex"
HEADER = "% Generated by scripts/funder_profile.py from data/funders.yaml and grants.bib; do not edit."
# Jim's role -> the clause it goes in, in printed order.
ROLES = [("PI", "PI of"), ("Co-PI", "Co-PI of"), ("Co", "a co-investigator or co-applicant on")]
NUMBERS = ["", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]


def funder_index(root: Path = ROOT) -> tuple[dict[str, dict], list[str]]:
    """{agency spelling: funder record}, and problems with data/funders.yaml."""
    idx, problems = {}, []
    for f in load_tagged(root / "data" / "funders.yaml").get("funders", []):
        if f.get("sector") not in SECTORS:
            problems.append(f"data/funders.yaml: '{f.get('name')}' has sector '{f.get('sector')}', "
                            f"not one of {', '.join(SECTORS)}")
        for a in f.get("agency", []) or []:
            idx[a] = f
    return idx, problems


def grants_by_funder(root: Path = ROOT) -> tuple[list[tuple], list[str]]:
    """[(grant entry, funder record)] for every grant in grants.bib, and problems:
    an agency that data/funders.yaml doesn't list."""
    idx, problems = funder_index(root)
    out = []
    for e in parse_bib(root / "grants.bib").entries:
        agency = e.fields.get("agency", "")
        f = idx.get(agency)
        if f is None:
            problems.append(f"{e.key}: agency '{agency}' is not in data/funders.yaml")
            continue
        out.append((e, f))
    return out, problems


def years(date: str) -> str:
    """'2017' -> 2017; '2017/2018' -> 2017--18; '2019/2021' -> 2019--21."""
    m = re.match(r"(\d{4})(?:-\d{2})?(?:/(\d{4}))?", date or "")
    if not m:
        return ""
    a, b = m.group(1), m.group(2)
    if not b or b == a:
        return a
    return f"{a}--{b[2:]}" if a[:2] == b[:2] else f"{a}--{b}"


def role_class(role: str) -> str:
    return role if role in ("PI", "Co-PI") else "Co"


def build(root: Path = ROOT) -> tuple[str, list[str]]:
    grants, problems = grants_by_funder(root)
    if problems:
        return "", problems
    funded = [(e, f) for e, f in grants
              if "status" not in e.fields and f["sector"] == "health"]
    clauses = []
    for role, lead in ROLES:
        mine = [(e, f) for e, f in funded if role_class(e.fields.get("role", "")) == role]
        by_funder: dict[str, list] = {}
        for e, f in sorted(mine, key=lambda ef: ef[0].fields.get("date", "")):
            by_funder.setdefault(f["name"], []).append(e)
        items = []
        for name, es in by_funder.items():
            spans = join_and([years(e.fields.get("date", "")) for e in es])
            name = tex_escape(name)
            if len(es) == 1:
                article = "an" if name[0] in "AEIOU" else "a"
                items.append(f"{article} {name} project ({spans})")
            else:
                n = NUMBERS[len(es)] if len(es) < len(NUMBERS) else str(len(es))
                items.append(f"{n} {name} grants ({spans})")
        if items:
            clauses.append(f"{lead} {join_and(items)}")
    if not clauses:
        return HEADER + "\n", []
    if len(clauses) == 3:
        body = f"{clauses[0]} and {clauses[1]}, and {clauses[2]}"
    else:
        body = " and ".join(clauses)
    return f"{HEADER}\nI was {body}.\n", []


def main(argv: list[str]) -> int:
    out = ROOT / OUT
    text, problems = build()
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    if "--check" in argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{OUT} is out of step; run python3 scripts/generate.py", file=sys.stderr)
            return 1
        return 0
    out.write_text(text, encoding="utf-8")
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
